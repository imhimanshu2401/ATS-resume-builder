import type { ExperienceItem, ResumeData } from '../types/ats';

export interface LatexInlineSpan {
  text: string;
  bold?: boolean;
  italic?: boolean;
  underline?: boolean;
  href?: string;
}

export interface LatexSubheadingBlock {
  kind: 'subheading';
  title: string;
  dates: string;
  subtitle: string;
  location: string;
  items: LatexInlineSpan[][];
}

export interface LatexParagraphBlock {
  kind: 'paragraph';
  spans: LatexInlineSpan[];
}

export interface LatexListBlock {
  kind: 'list';
  items: LatexInlineSpan[][];
}

export type LatexSectionBlock =
  | LatexSubheadingBlock
  | LatexParagraphBlock
  | LatexListBlock;

export interface LatexSectionPreview {
  title: string;
  blocks: LatexSectionBlock[];
}

export interface LatexDocumentPreview {
  name: string;
  contactItems: LatexInlineSpan[];
  sections: LatexSectionPreview[];
}

export function escapeLatex(text: string): string {
  return text
    .replace(/\\/g, '\\textbackslash{}')
    .replace(/&/g, '\\&')
    .replace(/%/g, '\\%')
    .replace(/\$/g, '\\$')
    .replace(/#/g, '\\#')
    .replace(/_/g, '\\_')
    .replace(/\{/g, '\\{')
    .replace(/\}/g, '\\}')
    .replace(/~/g, '\\textasciitilde{}')
    .replace(/\^/g, '\\textasciicircum{}');
}

export function unescapeLatex(text: string): string {
  return text
    .replace(/\\textbackslash\{\}/g, '\\')
    .replace(/\\textasciitilde\{\}/g, '~')
    .replace(/\\textasciicircum\{\}/g, '^')
    .replace(/\\&/g, '&')
    .replace(/\\%/g, '%')
    .replace(/\\\$/g, '$')
    .replace(/\\#/g, '#')
    .replace(/\\_/g, '_')
    .replace(/\\\{/g, '{')
    .replace(/\\\}/g, '}')
    .replace(/--+/g, '–')
    .replace(/\\\\/g, ' ')
    .replace(/\\vspace\{[^}]*\}/g, '')
    .replace(/\\small\b/g, '')
    .replace(/\\normalsize\b/g, '')
    .trim();
}

export function generateJakeLatex(resume: ResumeData): string {
  const safeName = escapeLatex(resume.name || 'Candidate Name');
  const contactParts: string[] = [];

  if (resume.phone.trim()) {
    contactParts.push(escapeLatex(resume.phone.trim()));
  }
  if (resume.email.trim()) {
    const email = resume.email.trim();
    contactParts.push(`\\href{mailto:${email}}{\\underline{${escapeLatex(email)}}}`);
  }
  if (resume.location.trim()) {
    contactParts.push(escapeLatex(resume.location.trim()));
  }
  if (resume.linkedin.trim()) {
    const rawLink = resume.linkedin.trim();
    const hrefUrl = /^https?:\/\//i.test(rawLink) ? rawLink : `https://${rawLink}`;
    contactParts.push(`\\href{${hrefUrl}}{\\underline{${escapeLatex(rawLink)}}}`);
  }

  const contactLine = contactParts.join(' $|$ ');

  const experienceBlocks = resume.experiences
    .map((exp) => {
      const bullets = exp.bullets
        .map((b) => b.trim())
        .filter(Boolean)
        .map((b) => `        \\resumeItem{${escapeLatex(b)}}`)
        .join('\n');

      return `    \\resumeSubheading
      {${escapeLatex(exp.title)}}{${escapeLatex(exp.dates)}}
      {${escapeLatex(exp.company)}}{${escapeLatex(exp.location)}}
      \\resumeItemListStart
${bullets || '        \\resumeItem{Delivered measurable project outcomes.}'}
      \\resumeItemListEnd`;
    })
    .join('\n\n');

  const skillsLine = resume.skills.map((s) => escapeLatex(s)).join(', ');
  const certsLine = resume.education.certifications.trim()
    ? ` \\\\\n     \\textbf{Certifications}{: ${escapeLatex(resume.education.certifications.trim())}}`
    : '';

  return `%-------------------------
% ATS-Friendly Resume in LaTeX (Jake's Resume Classic Single-Column)
% Generated by ATSPulse
%------------------------

\\documentclass[letterpaper,11pt]{article}

\\usepackage{latexsym}
\\usepackage[empty]{fullpage}
\\usepackage{titlesec}
\\usepackage{marvosym}
\\usepackage[usenames,dvipsnames]{color}
\\usepackage{verbatim}
\\usepackage{enumitem}
\\usepackage[hidelinks]{hyperref}
\\usepackage{fancyhdr}
\\usepackage[english]{babel}
\\usepackage{tabularx}

\\pagestyle{fancy}
\\fancyhf{}
\\fancyfoot{}
\\renewcommand{\\headrulewidth}{0pt}
\\renewcommand{\\footrulewidth}{0pt}

\\addtolength{\\oddsidemargin}{-0.5in}
\\addtolength{\\evensidemargin}{-0.5in}
\\addtolength{\\textwidth}{1in}
\\addtolength{\\topmargin}{-.5in}
\\addtolength{\\textheight}{1.0in}

\\urlstyle{same}
\\raggedbottom
\\raggedright
\\setlength{\\tabcolsep}{0in}

\\titleformat{\\section}{
  \\vspace{-4pt}\\scshape\\raggedright\\large
}{}{0em}{}[\\color{black}\\titlerule \\vspace{-5pt}]

\\newcommand{\\resumeItem}[1]{
  \\item\\small{
    {#1 \\vspace{-2pt}}
  }
}

\\newcommand{\\resumeSubheading}[4]{
  \\vspace{-2pt}\\item
    \\begin{tabular*}{0.97\\textwidth}[t]{l@{\\extracolsep{\\fill}}r}
      \\textbf{#1} & #2 \\\\
      \\textit{\\small#3} & \\textit{\\small #4} \\\\
    \\end{tabular*}\\vspace{-7pt}
}

\\newcommand{\\resumeItemListStart}{\\begin{itemize}}
\\newcommand{\\resumeItemListEnd}{\\end{itemize}\\vspace{-5pt}}
\\newcommand{\\resumeSubHeadingListStart}{\\begin{itemize}[leftmargin=0.15in, label={}]}
\\newcommand{\\resumeSubHeadingListEnd}{\\end{itemize}}

\\begin{document}

%----------HEADING----------
\\begin{center}
    \\textbf{\\Huge \\scshape ${safeName}} \\\\ \\vspace{1pt}
    \\small ${contactLine}
\\end{center}

%-----------PROFESSIONAL SUMMARY-----------
\\section{Professional Summary}
  \\small{${escapeLatex(resume.summary.trim())}}

%-----------TECHNICAL SKILLS-----------
\\section{Technical Skills}
  \\begin{itemize}[leftmargin=0.15in, label={}]
    \\small{\\item{
     \\textbf{Core Skills}{: ${skillsLine}}${certsLine}
    }}
  \\end{itemize}

%-----------EXPERIENCE-----------
\\section{Experience}
  \\resumeSubHeadingListStart
${experienceBlocks}
  \\resumeSubHeadingListEnd

%-----------EDUCATION-----------
\\section{Education}
  \\resumeSubHeadingListStart
    \\resumeSubheading
      {${escapeLatex(resume.education.school)}}{${escapeLatex(resume.education.year)}}
      {${escapeLatex(resume.education.degree)}}{${escapeLatex(resume.location)}}
  \\resumeSubHeadingListEnd

\\end{document}
`;
}

export function validateLatexSyntax(source: string): { valid: boolean; issue?: string } {
  let depth = 0;
  for (let i = 0; i < source.length; i++) {
    const ch = source[i];
    const prev = i > 0 ? source[i - 1] : '';
    if (ch === '%' && prev !== '\\') {
      while (i < source.length && source[i] !== '\n') i++;
      continue;
    }
    if (ch === '{' && prev !== '\\') depth++;
    else if (ch === '}' && prev !== '\\') {
      depth--;
      if (depth < 0) {
        return { valid: false, issue: 'Extra closing brace "}" detected.' };
      }
    }
  }

  if (depth !== 0) {
    return {
      valid: false,
      issue: `${depth} unclosed brace${depth > 1 ? 's' : ''} "{" detected.`,
    };
  }
  if (!source.includes('\\begin{document}') || !source.includes('\\end{document}')) {
    return {
      valid: false,
      issue: 'Missing \\begin{document} or \\end{document} wrapper.',
    };
  }
  return { valid: true };
}

function readBracedArg(
  input: string,
  startIndex: number,
): { value: string; nextIndex: number } | null {
  let i = startIndex;
  while (i < input.length && /\s/.test(input[i])) i++;
  if (i >= input.length || input[i] !== '{') return null;

  let depth = 0;
  let result = '';
  for (; i < input.length; i++) {
    const ch = input[i];
    const prev = i > 0 ? input[i - 1] : '';
    if (ch === '{' && prev !== '\\') {
      if (depth > 0) result += ch;
      depth++;
    } else if (ch === '}' && prev !== '\\') {
      depth--;
      if (depth === 0) {
        return { value: result, nextIndex: i + 1 };
      }
      result += ch;
    } else {
      result += ch;
    }
  }
  return null;
}

function stripLatexComments(source: string): string {
  return source
    .split('\n')
    .map((line) => {
      let out = '';
      for (let i = 0; i < line.length; i++) {
        if (line[i] === '%' && (i === 0 || line[i - 1] !== '\\')) {
          break;
        }
        out += line[i];
      }
      return out;
    })
    .join('\n');
}

export function parseInlineLatex(raw: string): LatexInlineSpan[] {
  const spans: LatexInlineSpan[] = [];
  const cleaned = raw
    .replace(/\\vspace\{[^}]*\}/g, '')
    .replace(/\\small\b/g, '')
    .replace(/\\normalsize\b/g, '')
    .replace(/\\Huge\b/g, '')
    .replace(/\\scshape\b/g, '')
    .replace(/\$\|\$/g, '|');

  let buffer = '';
  let i = 0;

  const flushBuffer = () => {
    if (buffer) {
      const text = unescapeLatex(buffer);
      if (text) spans.push({ text });
      buffer = '';
    }
  };

  while (i < cleaned.length) {
    if (cleaned.startsWith('\\textbf', i)) {
      const arg = readBracedArg(cleaned, i + 7);
      if (arg) {
        flushBuffer();
        const nested = parseInlineLatex(arg.value);
        for (const s of nested) spans.push({ ...s, bold: true });
        i = arg.nextIndex;
        continue;
      }
    }
    if (cleaned.startsWith('\\textit', i)) {
      const arg = readBracedArg(cleaned, i + 7);
      if (arg) {
        flushBuffer();
        const nested = parseInlineLatex(arg.value);
        for (const s of nested) spans.push({ ...s, italic: true });
        i = arg.nextIndex;
        continue;
      }
    }
    if (cleaned.startsWith('\\underline', i)) {
      const arg = readBracedArg(cleaned, i + 10);
      if (arg) {
        flushBuffer();
        const nested = parseInlineLatex(arg.value);
        for (const s of nested) spans.push({ ...s, underline: true });
        i = arg.nextIndex;
        continue;
      }
    }
    if (cleaned.startsWith('\\href', i)) {
      const urlArg = readBracedArg(cleaned, i + 5);
      if (urlArg) {
        const labelArg = readBracedArg(cleaned, urlArg.nextIndex);
        if (labelArg) {
          flushBuffer();
          const nested = parseInlineLatex(labelArg.value);
          for (const s of nested) {
            spans.push({ ...s, href: urlArg.value.trim() });
          }
          i = labelArg.nextIndex;
          continue;
        }
      }
    }
    if (cleaned.startsWith('\\small', i)) {
      const arg = readBracedArg(cleaned, i + 6);
      if (arg) {
        flushBuffer();
        spans.push(...parseInlineLatex(arg.value));
        i = arg.nextIndex;
        continue;
      }
    }
    if (cleaned.startsWith('\\\\', i)) {
      buffer += ' ';
      i += 2;
      continue;
    }

    buffer += cleaned[i];
    i++;
  }

  flushBuffer();
  return spans;
}

function spansToPlainText(spans: LatexInlineSpan[]): string {
  return spans.map((s) => s.text).join('');
}

function parseSectionBody(body: string): LatexSectionBlock[] {
  const blocks: LatexSectionBlock[] = [];
  let cursor = 0;

  let currentSubheading: LatexSubheadingBlock | null = null;
  let looseBullets: LatexInlineSpan[][] = [];

  const flushSubheading = () => {
    if (currentSubheading) {
      blocks.push(currentSubheading);
      currentSubheading = null;
    }
  };

  const flushLooseBullets = () => {
    if (looseBullets.length > 0) {
      blocks.push({ kind: 'list', items: looseBullets });
      looseBullets = [];
    }
  };

  while (cursor < body.length) {
    const nextSub = body.indexOf('\\resumeSubheading', cursor);
    const nextProj = body.indexOf('\\resumeProjectHeading', cursor);
    const nextItem = body.indexOf('\\resumeItem{', cursor);
    const nextRawItem = body.indexOf('\\item{', cursor);

    const candidates = [
      { type: 'sub', pos: nextSub },
      { type: 'proj', pos: nextProj },
      { type: 'ritem', pos: nextItem },
      { type: 'item', pos: nextRawItem },
    ].filter((c) => c.pos >= 0);

    if (candidates.length === 0) break;
    candidates.sort((a, b) => a.pos - b.pos);
    const next = candidates[0];

    if (next.type === 'sub') {
      flushLooseBullets();
      flushSubheading();
      const a1 = readBracedArg(body, next.pos + '\\resumeSubheading'.length);
      const a2 = a1 ? readBracedArg(body, a1.nextIndex) : null;
      const a3 = a2 ? readBracedArg(body, a2.nextIndex) : null;
      const a4 = a3 ? readBracedArg(body, a3.nextIndex) : null;
      if (a1 && a2 && a3 && a4) {
        currentSubheading = {
          kind: 'subheading',
          title: spansToPlainText(parseInlineLatex(a1.value)),
          dates: spansToPlainText(parseInlineLatex(a2.value)),
          subtitle: spansToPlainText(parseInlineLatex(a3.value)),
          location: spansToPlainText(parseInlineLatex(a4.value)),
          items: [],
        };
        cursor = a4.nextIndex;
        continue;
      }
      cursor = next.pos + 17;
    } else if (next.type === 'proj') {
      flushLooseBullets();
      flushSubheading();
      const a1 = readBracedArg(body, next.pos + '\\resumeProjectHeading'.length);
      const a2 = a1 ? readBracedArg(body, a1.nextIndex) : null;
      if (a1 && a2) {
        currentSubheading = {
          kind: 'subheading',
          title: spansToPlainText(parseInlineLatex(a1.value)),
          dates: spansToPlainText(parseInlineLatex(a2.value)),
          subtitle: '',
          location: '',
          items: [],
        };
        cursor = a2.nextIndex;
        continue;
      }
      cursor = next.pos + 21;
    } else if (next.type === 'ritem') {
      const arg = readBracedArg(body, next.pos + '\\resumeItem'.length);
      if (arg) {
        const spans = parseInlineLatex(arg.value);
        if (currentSubheading) {
          currentSubheading.items.push(spans);
        } else {
          looseBullets.push(spans);
        }
        cursor = arg.nextIndex;
        continue;
      }
      cursor = next.pos + 11;
    } else {
      const arg = readBracedArg(body, next.pos + '\\item'.length);
      if (arg) {
        const spans = parseInlineLatex(arg.value);
        if (currentSubheading) {
          currentSubheading.items.push(spans);
        } else {
          looseBullets.push(spans);
        }
        cursor = arg.nextIndex;
        continue;
      }
      cursor = next.pos + 5;
    }
  }

  flushLooseBullets();
  flushSubheading();

  if (blocks.length === 0) {
    const cleaned = body
      .replace(/\\resumeSubHeadingListStart|\\resumeSubHeadingListEnd/g, '')
      .replace(/\\resumeItemListStart|\\resumeItemListEnd/g, '')
      .replace(/\\begin\{itemize\}(?:\[[^\]]*\])?|\\end\{itemize\}/g, '')
      .trim();
    const spans = parseInlineLatex(cleaned);
    if (spans.length > 0) {
      blocks.push({ kind: 'paragraph', spans });
    }
  }

  return blocks;
}

export function parseLatexToPreview(source: string): LatexDocumentPreview {
  const noComments = stripLatexComments(source);
  const docStart = noComments.indexOf('\\begin{document}');
  const docEnd = noComments.lastIndexOf('\\end{document}');
  const body =
    docStart >= 0
      ? noComments.slice(
          docStart + '\\begin{document}'.length,
          docEnd > docStart ? docEnd : undefined,
        )
      : noComments;

  // Header inside \begin{center}...\end{center}
  let name = 'Candidate Name';
  let contactItems: LatexInlineSpan[] = [];
  const centerMatch = body.match(/\\begin\{center\}([\s\S]*?)\\end\{center\}/);
  if (centerMatch) {
    const centerLines = centerMatch[1]
      .split('\\\\')
      .map((l) => l.trim())
      .filter(Boolean);
    if (centerLines[0]) {
      name = spansToPlainText(parseInlineLatex(centerLines[0])).trim() || name;
    }
    if (centerLines[1]) {
      contactItems = parseInlineLatex(centerLines[1]);
    }
  }

  // Extract \section{Title} slices
  const sections: LatexSectionPreview[] = [];
  const sectionMatches: { title: string; start: number; bodyStart: number }[] = [];
  let searchPos = 0;
  while (searchPos < body.length) {
    const idx = body.indexOf('\\section', searchPos);
    if (idx < 0) break;
    const arg = readBracedArg(body, idx + '\\section'.length);
    if (arg) {
      sectionMatches.push({
        title: spansToPlainText(parseInlineLatex(arg.value)),
        start: idx,
        bodyStart: arg.nextIndex,
      });
      searchPos = arg.nextIndex;
    } else {
      searchPos = idx + 8;
    }
  }

  for (let i = 0; i < sectionMatches.length; i++) {
    const current = sectionMatches[i];
    const nextStart =
      i + 1 < sectionMatches.length ? sectionMatches[i + 1].start : body.length;
    const sectionBody = body.slice(current.bodyStart, nextStart);
    sections.push({
      title: current.title,
      blocks: parseSectionBody(sectionBody),
    });
  }

  return { name, contactItems, sections };
}

export function latexToPlainText(source: string): string {
  const preview = parseLatexToPreview(source);
  const parts: string[] = [
    preview.name,
    spansToPlainText(preview.contactItems),
  ];

  for (const section of preview.sections) {
    parts.push(section.title.toUpperCase());
    for (const block of section.blocks) {
      if (block.kind === 'paragraph') {
        parts.push(spansToPlainText(block.spans));
      } else if (block.kind === 'list') {
        for (const item of block.items) {
          parts.push(`- ${spansToPlainText(item)}`);
        }
      } else if (block.kind === 'subheading') {
        parts.push(`${block.title} | ${block.subtitle} (${block.dates})`);
        for (const item of block.items) {
          parts.push(`- ${spansToPlainText(item)}`);
        }
      }
    }
  }

  return parts.filter(Boolean).join('\n');
}

export function extractResumeDataFromLatex(
  source: string,
  fallback: ResumeData,
): ResumeData {
  const preview = parseLatexToPreview(source);
  const contactText = spansToPlainText(preview.contactItems);
  const contactParts = contactText
    .split('|')
    .map((s) => s.trim())
    .filter(Boolean);

  const email = contactParts.find((p) => p.includes('@')) || fallback.email;
  const linkedin =
    contactParts.find((p) => /linkedin\.com|github\.com/i.test(p)) || fallback.linkedin;
  const phone =
    contactParts.find((p) => /\d{3}/.test(p) && !p.includes('@')) || fallback.phone;
  const location =
    contactParts.find(
      (p) =>
        p !== email &&
        p !== linkedin &&
        p !== phone &&
        p.length > 2,
    ) || fallback.location;

  let summary = fallback.summary;
  let skills = [...fallback.skills];
  let certifications = fallback.education.certifications;
  const experiences: ExperienceItem[] = [];
  let education = { ...fallback.education };

  for (const section of preview.sections) {
    const titleLower = section.title.toLowerCase();

    if (titleLower.includes('summary') || titleLower.includes('profile')) {
      const text = section.blocks
        .map((b) =>
          b.kind === 'paragraph'
            ? spansToPlainText(b.spans)
            : b.kind === 'list'
              ? b.items.map(spansToPlainText).join(' ')
              : '',
        )
        .filter(Boolean)
        .join(' ')
        .trim();
      if (text) summary = text;
    } else if (titleLower.includes('skill') || titleLower.includes('technolog')) {
      const listItems = section.blocks.flatMap((b) =>
        b.kind === 'list'
          ? b.items.map(spansToPlainText)
          : b.kind === 'paragraph'
            ? [spansToPlainText(b.spans)]
            : [],
      );
      for (const line of listItems) {
        if (/certifications?\s*:/i.test(line)) {
          certifications = line.replace(/^.*certifications?\s*:\s*/i, '').trim();
        } else {
          const cleaned = line.replace(/^[^:]{1,25}:\s*/, '');
          const parsed = cleaned
            .split(',')
            .map((s) => s.trim())
            .filter(Boolean);
          if (parsed.length > 0) skills = parsed;
        }
      }
    } else if (titleLower.includes('experience') || titleLower.includes('employment')) {
      for (const block of section.blocks) {
        if (block.kind === 'subheading') {
          experiences.push({
            id: `exp-${experiences.length + 1}`,
            title: block.title || 'Role Title',
            company: block.subtitle || 'Company',
            location: block.location || location,
            dates: block.dates || '2021 – Present',
            bullets: block.items.map(spansToPlainText).filter(Boolean),
          });
        }
      }
    } else if (titleLower.includes('education')) {
      const sub = section.blocks.find((b) => b.kind === 'subheading');
      if (sub && sub.kind === 'subheading') {
        education = {
          school: sub.title || fallback.education.school,
          year: sub.dates || fallback.education.year,
          degree: sub.subtitle || fallback.education.degree,
          certifications,
        };
      }
    }
  }

  return {
    name: preview.name || fallback.name,
    email,
    phone,
    location,
    linkedin,
    summary,
    skills,
    experiences: experiences.length > 0 ? experiences : fallback.experiences,
    education: { ...education, certifications },
  };
}
